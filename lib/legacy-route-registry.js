export function humanizeSlug(slug) {
  return slug
    .split('-')
    .filter(Boolean)
    .map((word) => word === 'nadra' ? 'NADRA' : word === 'fbr' ? 'FBR' : word === 'ntn' ? 'NTN' : word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ')
}
